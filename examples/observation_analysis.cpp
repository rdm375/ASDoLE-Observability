#include "asdole/analysis.hpp"
#include "asdole/observations.hpp"

#include <algorithm>
#include <cmath>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <span>
#include <stdexcept>
#include <string>
#include <vector>

namespace {

using asdole::DenseMatrix;
using asdole::Vector;

constexpr double theta = 0.7;
constexpr double final_time = 4.0;
constexpr int steps = 80;
constexpr double h = final_time / steps;

const asdole::HessianFunction zero_hessian = [](std::span<const double>, asdole::HessianTensor& tensor) {
    for (auto& component : tensor) component.fill(0.0);
};

asdole::Stepper make_stepper() {
    const auto rhs = [](std::span<const double> y, std::span<double> f) {
        f[0] = -y[0] + y[1];
        f[1] = -2.0 * y[1];
    };
    const auto jacobian = [](std::span<const double>, DenseMatrix& j) {
        j(0, 0) = -1.0; j(0, 1) = 1.0;
        j(1, 0) = 0.0;  j(1, 1) = -2.0;
    };
    return asdole::Stepper(rhs, jacobian, theta);
}

std::vector<double> make_times() {
    std::vector<double> times(steps + 1);
    for (int k = 0; k <= steps; ++k) times[k] = k * h;
    return times;
}

std::vector<Vector> integrate(const asdole::Stepper& stepper, const Vector& initial) {
    std::vector<Vector> states(steps + 1);
    states[0] = initial;
    for (int k = 0; k < steps; ++k) states[k + 1] = stepper.step(states[k], h).state;
    return states;
}

double gradient_norm(const Vector& gradient) {
    double sum = 0.0;
    for (double value : gradient) sum += value * value;
    return std::sqrt(sum);
}

} // namespace

int main(int argc, char** argv) {
    const auto stepper = make_stepper();
    const auto times = make_times();
    DenseMatrix observation(1, 2); // One sensor observes y_1; state dimension is two.
    observation(0, 0) = 1.0;
    DenseMatrix precision(1, 1);
    precision(0, 0) = 1.0;

    const Vector truth_initial{1.0, 0.7};
    const Vector estimate_initial{1.1, 0.4};
    const auto truth = integrate(stepper, truth_initial);
    const auto trajectory = integrate(stepper, estimate_initial);
    std::vector<Vector> data(times.size());
    for (std::size_t k = 0; k < times.size(); ++k)
        data[k] = asdole::detail::matvec(observation, truth[k]);

    const auto objective = asdole::trapezoidal_observation_objective(
        times, trajectory, data, observation, precision);

    const asdole::DiscreteTrajectoryLinearization trajectory_linearization(
        stepper, zero_hessian, trajectory, std::vector<double>(steps, h));
    const auto sensor = asdole::dense_observation_operator(observation);
    std::vector<asdole::ObservationSample> samples;
    samples.reserve(times.size());
    for (std::size_t k = 0; k < times.size(); ++k) {
        const double weight = k == 0 ? 0.5 * (times[1] - times[0])
            : (k + 1 == times.size() ? 0.5 * (times[k] - times[k - 1])
                                     : 0.5 * (times[k + 1] - times[k - 1]));
        samples.push_back({k, sensor, weight, {}});
    }
    const asdole::ObservationSensitivityOperator sensitivity_operator(
        trajectory_linearization, std::move(samples));

    // Each column is generated by a matrix-free TLM action, not by storing
    // every state-transition Jacobian along the trajectory.
    const Vector observation_sensitivity_y1 = sensitivity_operator.apply(Vector{1.0, 0.0});
    const Vector observation_sensitivity_y2 = sensitivity_operator.apply(Vector{0.0, 1.0});
    const auto observability = asdole::analyze_observability(sensitivity_operator);

    // The discrete adjoint accumulates exactly the node loads returned by the
    // trapezoidal objective and pulls them through the same ASDoLE steps.
    std::vector<Vector> objective_costate(steps + 1, Vector(2, 0.0));
    objective_costate.back() = objective.state_gradient.back();
    for (int k = steps - 1; k >= 0; --k) {
        objective_costate[k] = asdole::adjoint_step(
            stepper, zero_hessian, trajectory[k], h, objective_costate[k + 1]);
        for (std::size_t i = 0; i < objective_costate[k].size(); ++i)
            objective_costate[k][i] += objective.state_gradient[k][i];
    }
    const Vector& adjoint = objective_costate.front();

    Vector residual(times.size());
    for (std::size_t k = 0; k < times.size(); ++k)
        residual[k] = asdole::detail::matvec(observation, trajectory[k])[0] - data[k][0];
    const Vector matrix_free_adjoint_gradient = sensitivity_operator.weighted_transpose_apply(residual);
    Vector tlm_gradient(2, 0.0);
    for (std::size_t k = 0; k < times.size(); ++k) {
        const double weight = k == 0 ? 0.5 * (times[1] - times[0])
            : (k + 1 == times.size() ? 0.5 * (times[k] - times[k - 1])
                                     : 0.5 * (times[k + 1] - times[k - 1]));
        tlm_gradient[0] += observation_sensitivity_y1[k] * weight * residual[k];
        tlm_gradient[1] += observation_sensitivity_y2[k] * weight * residual[k];
    }

    Vector finite_difference_gradient(2);
    constexpr double epsilon = 1.0e-6;
    for (int j = 0; j < 2; ++j) {
        Vector plus = estimate_initial, minus = estimate_initial;
        plus[j] += epsilon; minus[j] -= epsilon;
        const double jp = asdole::trapezoidal_observation_objective(
            times, integrate(stepper, plus), data, observation, precision).value;
        const double jm = asdole::trapezoidal_observation_objective(
            times, integrate(stepper, minus), data, observation, precision).value;
        finite_difference_gradient[j] = (jp - jm) / (2.0 * epsilon);
    }

    const Vector terminal_measurement_cotangent = sensor.transpose(Vector{1.0});
    std::vector<Vector> terminal_observation_adjoint(steps + 1);
    for (int k = 0; k <= steps; ++k)
        terminal_observation_adjoint[k] = trajectory_linearization.pullback_to_node(
            terminal_measurement_cotangent, k, steps);

    const std::filesystem::path csv_path = argc > 1
        ? std::filesystem::path(argv[1])
        : std::filesystem::path("results/observation-analysis/observation_sensitivity.csv");
    if (!csv_path.parent_path().empty()) std::filesystem::create_directories(csv_path.parent_path());
    std::ofstream csv(csv_path);
    if (!csv) throw std::runtime_error("could not open observation sensitivity CSV output");
    csv << "time,state_y1,state_y2,observed_y1,d_observation_d_initial_y1,"
           "d_observation_d_initial_y2,terminal_adjoint_y1,terminal_adjoint_y2,"
           "objective_costate_y1,objective_costate_y2\n";
    csv << std::setprecision(16);
    for (int k = 0; k <= steps; ++k)
        csv << times[k] << ',' << trajectory[k][0] << ',' << trajectory[k][1] << ','
            << trajectory[k][0] << ','
            << observation_sensitivity_y1[k] << ',' << observation_sensitivity_y2[k] << ','
            << terminal_observation_adjoint[k][0] << ',' << terminal_observation_adjoint[k][1] << ','
            << objective_costate[k][0] << ',' << objective_costate[k][1] << '\n';

    std::cout << std::setprecision(12)
              << "model= y1'=-y1+y2, y2'=-2y2\n"
              << "theta=" << theta << " steps=" << steps << " dt=" << h << " final_time=" << final_time << '\n'
              << "observation_matrix_shape=" << observation.rows() << 'x' << observation.cols() << '\n'
              << "observation_matrix=[1,0]\n"
              << "truth_initial=[1,0.7] estimate_initial=[1.1,0.4]\n"
              << "objective_trapezoid=" << objective.value << '\n'
              << "weighted_observation_sensitivity_shape=" << sensitivity_operator.output_dimension()
              << 'x' << sensitivity_operator.input_dimension() << '\n'
              << "quadrature_weighted_observability_rank=" << observability.numerical_rank << '\n'
              << "quadrature_weighted_observability_singular_values=[";
    for (std::size_t i = 0; i < observability.singular_values.size(); ++i) {
        if (i) std::cout << ',';
        std::cout << observability.singular_values[i];
    }
    std::cout << "]\n"
              << "quadrature_weighted_observability_condition=" << observability.condition_number << '\n'
              << "objective_gradient_tlm=[" << tlm_gradient[0] << ',' << tlm_gradient[1] << "]\n"
              << "objective_gradient_adjoint=[" << adjoint[0] << ',' << adjoint[1] << "]\n"
              << "objective_gradient_matrix_free_adjoint=[" << matrix_free_adjoint_gradient[0]
              << ',' << matrix_free_adjoint_gradient[1] << "]\n"
              << "objective_gradient_fd=[" << finite_difference_gradient[0] << ','
              << finite_difference_gradient[1] << "]\n"
              << "tlm_adjoint_defect=" << std::hypot(tlm_gradient[0] - adjoint[0], tlm_gradient[1] - adjoint[1]) << '\n'
              << "matrix_free_pullback_defect=" << std::hypot(
                    matrix_free_adjoint_gradient[0] - adjoint[0],
                    matrix_free_adjoint_gradient[1] - adjoint[1]) << '\n'
              << "adjoint_fd_defect=" << std::hypot(adjoint[0] - finite_difference_gradient[0],
                                                       adjoint[1] - finite_difference_gradient[1]) << '\n'
              << "gradient_norm=" << gradient_norm(adjoint) << '\n';
    std::cout << "observation_sensitivity_csv=" << csv_path << '\n';
}
